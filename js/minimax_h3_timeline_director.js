  bindAssetReorder(bin, kind, label, group = null) {
    const clearMarkers=()=>{
      for(const card of this.root.querySelectorAll(".m3td-asset"))card.classList.remove("dragging","drop-before","drop-after");
      for(const target of this.root.querySelectorAll(".m3td-bin-list.drag-over"))target.classList.remove("drag-over");
    };

    // Image and audio library bins accept assets dragged from sibling categories.
    // The asset ID remains unchanged, so existing segment assignments stay intact.
    if((kind==="images" || kind==="audios") && group){
      bin.ondragover=e=>{
        if(!this.assetDrag || this.assetDrag.source!=="library" || this.assetDrag.kind!==kind || this.assetDrag.sourceGroup===group)return;
        e.preventDefault();
        e.stopPropagation();
        if(e.dataTransfer)e.dataTransfer.dropEffect="move";
        bin.classList.add("drag-over");
      };
      bin.ondragleave=e=>{
        if(!bin.contains(e.relatedTarget))bin.classList.remove("drag-over");
      };
      bin.ondrop=e=>{
        if(!this.assetDrag || this.assetDrag.source!=="library" || this.assetDrag.kind!==kind || this.assetDrag.sourceGroup===group)return;
        e.preventDefault();
        e.stopPropagation();
        const asset=this.state[kind].find(item=>String(item.id)===String(this.assetDrag.id));
        if(!asset){this.assetDrag=null;clearMarkers();return;}
        if(kind==="audios")asset.audioGroup=group;
        else asset.group=group;
        this.assetDrag=null;
        clearMarkers();
        this.sync();
        this.render();
        this.setStatus(kind==="images"
          ? `图片已移动到${group==="character"?"人物":group==="props"?"道具":"场景"}分类`
          : `音频已移动到${group==="music"?"音乐参考":"音频参考"}分类`);
      };
    }

    for(const card of bin.querySelectorAll(".m3td-asset")){
      card.ondragstart=e=>{
        if(e.target.closest?.("button,select,input")){e.preventDefault();return;}
        const id=String(card.dataset.assetId);
        if(kind==="images"){
          if(!this.imageAssetSelection.has(id)){this.imageAssetSelection=new Set([id]);this.imageAssetSelectionAnchor=id;}
          this.assetDrag={kind,id,ids:[...this.imageAssetSelection],source:"library",sourceGroup:group};
        }else this.assetDrag={kind,id,source:"library",sourceGroup:group};
        card.classList.add("dragging");
        e.dataTransfer.effectAllowed="copyMove";
        e.dataTransfer.setData("text/plain",card.dataset.assetId);
      };
      card.ondragover=e=>{
        if(!this.assetDrag || this.assetDrag.source!=="library" || this.assetDrag.kind!==kind || this.assetDrag.id===card.dataset.assetId)return;
        e.preventDefault();
        e.stopPropagation();
        if(e.dataTransfer)e.dataTransfer.dropEffect="move";
        const rect=card.getBoundingClientRect(),after=e.clientX>=rect.left+rect.width/2;
        for(const other of this.root.querySelectorAll(".m3td-asset"))other.classList.remove("drop-before","drop-after");
        card.classList.add(after?"drop-after":"drop-before");
      };
      card.ondrop=e=>{
        if(!this.assetDrag || this.assetDrag.source!=="library" || this.assetDrag.kind!==kind)return;
        e.preventDefault();
        e.stopPropagation();
        const draggedId=this.assetDrag.id;
        const targetId=card.dataset.assetId;
        const rect=card.getBoundingClientRect(),after=e.clientX>=rect.left+rect.width/2;
        const crossCategory=(kind==="images" || kind==="audios") && this.assetDrag.sourceGroup!==group;
        let changed=false;
        if(crossCategory){
          const asset=this.state[kind].find(item=>String(item.id)===String(draggedId));
          if(asset){
            if(kind==="audios")asset.audioGroup=group;
            else asset.group=group;
            reorderById(this.state[kind],draggedId,targetId,after);
            changed=true;
          }
        }else{
          changed=reorderById(this.state[kind],draggedId,targetId,after);
        }
        this.assetDrag=null;
        clearMarkers();
        if(changed){
          this.sync();
          this.render();
          this.setStatus(crossCategory
            ? (kind==="images"
              ? `图片已移动到${group==="character"?"人物":group==="props"?"道具":"场景"}分类`
              : `音频已移动到${group==="music"?"音乐参考":"音频参考"}分类`)
            : tr(label));
        }
      };
      card.ondragend=()=>{
        this.assetDrag=null;
        clearMarkers();
      };
    }
  }

