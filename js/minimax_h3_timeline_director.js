function normalizeState(raw) {
  const base = emptyState();
  if (!raw || typeof raw !== "object") return base;
  base.globalPrompt = String(raw.globalPrompt || "");
  base.secondPass = raw.secondPass === true;
  base.secondPassModel = String(raw.secondPassModel || "");
  base.secondPassHighSteps = Math.max(1, Math.floor(num(raw.secondPassHighSteps, 4)));
  base.selection.start = Math.max(0, num(raw.selection?.start, 0));
  base.selection.duration = Math.max(5 / 24, num(raw.selection?.duration, 5));
  base.videoAudioEnabled = raw.videoAudioEnabled !== false;
  base.videoClips = Array.isArray(raw.videoClips) ? raw.videoClips.filter(x => x?.file).map(c => ({
    id: c.id || uid(), file: c.file, name: c.name || c.file.split(/[\\/]/).pop(), start: Math.max(0, num(c.start)),
    duration: Math.max(5 / 24, num(c.duration, 5)), trimStart: Math.max(0, num(c.trimStart)),
    sourceDuration: Math.max(0, num(c.sourceDuration, c.duration)), hasAudio: c.hasAudio !== false,
    referenceMode: ["guide","edit","boundary"].includes(c.referenceMode) ? c.referenceMode : "guide",
    referenceWidth: num(c.referenceWidth) > 0 ? alignReferenceDimension(c.referenceWidth) : 0,
    referenceHeight: num(c.referenceHeight) > 0 ? alignReferenceDimension(c.referenceHeight) : 0,
    proxy: c.proxy || "",
    peaks: Array.isArray(c.peaks) ? c.peaks : [],
  })) : [];
  base.images = Array.isArray(raw.images) ? raw.images.filter(x => x?.file).map(a => ({ id:a.id || uid(), ...a })) : [];
  base.audios = Array.isArray(raw.audios) ? raw.audios.filter(x => x?.file).map(a => ({ ...a, id:a.id || uid(), audioMode:a.audioMode==="locked"?"locked":"reference" })) : [];
  const imageIds=new Set(base.images.map(a=>String(a.id))),audioIds=new Set(base.audios.map(a=>String(a.id)));
  const rawConfig=raw.segmentConfig&&typeof raw.segmentConfig==="object"?raw.segmentConfig:{};
  const rawCount=Math.floor(num(rawConfig.count,0));
  const count=clamp(rawCount,1,64);
  const sourceSegments=Array.isArray(rawConfig.segments)?rawConfig.segments:[];
  const migratedFromUnsegmented=rawCount<1;
  const globalOverlapFrames=Math.max(0,Math.floor(num(rawConfig.globalOverlapFrames,39)));
  const defaultWindows=createWindows([],count,base.selection.duration*24,globalOverlapFrames);
  base.segmentConfig={count,activeIndex:clamp(Math.floor(num(rawConfig.activeIndex)),0,count-1),globalOverlapFrames,mode:migratedFromUnsegmented||rawConfig.mode==="timeline"?"timeline":"legacy",groups:Array.isArray(rawConfig.groups)?rawConfig.groups.filter(g=>g&&typeof g==="object").map(g=>({id:String(g.id||uid()),name:String(g.name||"未命名分组")})):[],segments:Array.from({length:count},(_,index)=>{
    const segment=sourceSegments[index]&&typeof sourceSegments[index]==="object"?sourceSegments[index]:{};
    const fallback=defaultWindows[index];
    return {...fallback,...segment,
      images:(migratedFromUnsegmented&&index===0?[...imageIds]:normalizedAssetIds(segment.images,imageIds)).slice(0,MAX_SEGMENT_IMAGES),
      audios:(migratedFromUnsegmented&&index===0?[...audioIds]:normalizedAssetIds(segment.audios,audioIds)).slice(0,MAX_SEGMENT_AUDIOS),
      prompt:String(segment.prompt||"")};
  })};
  return base;
}

